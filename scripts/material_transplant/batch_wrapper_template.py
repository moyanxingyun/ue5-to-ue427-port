# -*- coding: utf-8 -*-
"""Generate restart-safe master-material batch wrappers.

Environment:
    Plain Python 3.7+. Run the generated wrappers in UE 4.27 Editor Python.

Use:
    python batch_wrapper_template.py --config config.json --output-dir wrappers --batch-size 8

Output:
    Run_01_08.py, Run_09_16.py, ... Each wrapper calls build_ue427.py through
    runpy.run_path with MASTER_RANGE and other runtime switches in init_globals.
    Restart UE between wrappers so the editor releases compiled material memory.
"""
import argparse
import json
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
SCRIPTS_ROOT = os.path.dirname(SCRIPT_DIR)
if SCRIPTS_ROOT not in sys.path:
    sys.path.insert(0, SCRIPTS_ROOT)

from portkit_config import load_config, path_value
from material_transplant.planner import plan, report_unsupported
from material_transplant.t3d_parser import load_graphs


WRAPPER = '''# -*- coding: utf-8 -*-
# Generated by PortKit batch_wrapper_template.py.
# UE 4.27 Editor Python, Cmd mode:
#   py "{wrapper_path}"
# Rebuilds switch combinations {first} through {last}. Restart UE before the
# next wrapper. Output and failures are recorded in the normal rebuild report.
import os
import runpy
import sys

BUILDER = {builder!r}
CONFIG = {config!r}
os.environ["PORTKIT_CONFIG"] = CONFIG
sys.argv = [BUILDER, "--config", CONFIG]
runpy.run_path(
    BUILDER,
    init_globals={{
        "MASTER_RANGE": ({first}, {last}),
        "ONLY_COMBOS": None,
        "DO_TEXTURES": {do_textures!r},
        "DO_MESHES": False,
        "REBUILD_EXISTING": {rebuild_existing!r},
    }},
    run_name="__main__",
)
'''


def _combo_count(config):
    material = config.get("material", {})
    graphs = load_graphs(path_value(config, "paths", "dumps"))
    with open(
        path_value(config, "paths", "materials_json"),
        "r",
        encoding="utf-8",
    ) as handle:
        infos = json.load(handle)
    data = plan(
        graphs,
        infos,
        material.get("master_name"),
        material.get("func_dir"),
    )
    return data, graphs


def generate(config_path, output_dir, batch_size):
    config = load_config(config_path)
    material = config.get("material", {})
    data, graphs = _combo_count(config)
    if not data["combos"]:
        raise ValueError("No switch combinations were planned")
    if batch_size < 1:
        raise ValueError("batch size must be at least 1")
    if not os.path.isdir(output_dir):
        os.makedirs(output_dir)
    builder = os.path.join(SCRIPT_DIR, "build_ue427.py")
    probe_path = path_value(config, "paths", "probe_427")
    probe = None
    if probe_path and os.path.isfile(probe_path):
        with open(probe_path, "r", encoding="utf-8") as handle:
            probe = json.load(handle)
    check = report_unsupported(
        graphs,
        probe,
        len(data["combos"]),
        int(material.get("max_combos", 50)),
    )
    outputs = []
    for first in range(1, len(data["combos"]) + 1, batch_size):
        last = min(first + batch_size - 1, len(data["combos"]))
        output = os.path.join(
            output_dir, "Run_%02d_%02d.py" % (first, last)
        )
        text = WRAPPER.format(
            wrapper_path=output,
            builder=builder,
            config=os.path.abspath(config["_config_path"]),
            first=first,
            last=last,
            do_textures=first == 1,
            rebuild_existing=bool(material.get("rebuild_existing", False)),
        )
        with open(output, "w", encoding="utf-8") as handle:
            handle.write(text)
        outputs.append(output)
    return outputs, check, len(data["combos"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True)
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--batch-size", type=int, default=8)
    args = parser.parse_args()
    outputs, check, combo_count = generate(
        args.config, args.output_dir, args.batch_size
    )
    print(
        "combinations=%d wrappers=%d needs_confirm=%s"
        % (combo_count, len(outputs), check["needs_confirm"])
    )
    for output in outputs:
        print(output)


if __name__ == "__main__":
    main()
